#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { parseArgs } from 'node:util';

import { build as esbuild } from 'esbuild';
import { inject } from 'postject';

import { ensureNodeBinary, describeTargets } from './lib/node-dist.mjs';

const APP_DIR = path.resolve(import.meta.dirname, '..');
const REPO_DIR = path.resolve(APP_DIR, '..');
// Shipped next to every artifact so a server-wide risk policy is one edit away.
const RISK_EXAMPLE = path.join(REPO_DIR, 'risk-policy.example.json');
const SENTINEL_FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

const TARGETS = {
  'win-x64': { platform: 'win32', arch: 'x64', extension: '.exe' },
  'win-arm64': { platform: 'win32', arch: 'arm64', extension: '.exe' },
  'linux-x64': { platform: 'linux', arch: 'x64', extension: '' },
  'linux-arm64': { platform: 'linux', arch: 'arm64', extension: '' },
};
const DEFAULT_TARGETS = ['win-x64', 'linux-x64'];

function log(message) {
  console.log(`• ${message}`);
}

function parseCli(argv) {
  const { values } = parseArgs({
    args: argv,
    allowPositionals: false,
    options: {
      target: { type: 'string', short: 't' },
      out: { type: 'string' },
      'build-dir': { type: 'string' },
      'skip-frontend': { type: 'boolean' },
      portable: { type: 'boolean' },
      'bundle-only': { type: 'boolean' },
      'no-smoke': { type: 'boolean' },
      help: { type: 'boolean', short: 'h' },
    },
  });
  if (values.help) {
    console.log(`Usage: npm run standalone -- [options]

  -t, --target <list>   ${Object.keys(TARGETS).join(', ')} or all (default ${DEFAULT_TARGETS.join(', ')})
      --out <dir>       Where the output is written (default ../release)
      --build-dir <dir> Intermediate files (default build/sea)
      --skip-frontend   Reuse the existing dist/ instead of running npm run build
      --portable        Write portable folders (signed node + app.cjs + launcher) instead
                        of single executables – use this when Smart App Control objects
                        to the injected binary
      --bundle-only     Write just app.cjs (+ .sha256): run it with \`node app.cjs\`
      --no-smoke        Skip the post-build HTTP smoke test of the host build`);
    process.exit(0);
  }
  return values;
}

function resolveTargets(value) {
  const requested = (value ?? DEFAULT_TARGETS.join(','))
    .split(',')
    .map((name) => name.trim().toLowerCase())
    .filter(Boolean);
  const names = requested.includes('all') ? Object.keys(TARGETS) : requested;
  for (const name of names) {
    if (!(name in TARGETS)) {
      throw new Error(`Unknown target "${name}". Supported: ${describeTargets().join(', ')}, all`);
    }
  }
  return [...new Set(names)];
}

function readPackage() {
  return JSON.parse(fs.readFileSync(path.join(APP_DIR, 'package.json'), 'utf8'));
}

function appTitle(pkg) {
  return pkg.productName ?? pkg.name;
}

function buildFrontend() {
  log('building the SPA (npm run build)');
  const result = spawnSync('npm run build', { cwd: APP_DIR, stdio: 'inherit', shell: true });
  if (result.status !== 0) throw new Error('npm run build failed');
}

function collectFiles(directory) {
  const files = {};
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else {
        const key = `/${path.relative(directory, full).split(path.sep).join('/')}`;
        files[key] = fs.readFileSync(full);
      }
    }
  };
  walk(directory);
  return files;
}

function writeEmbeddedModule({ buildDir, files, pkg }) {
  const entries = Object.entries(files).sort(([left], [right]) => (left < right ? -1 : 1));
  if (!entries.some(([key]) => key === '/index.html')) {
    throw new Error('dist/index.html is missing – run the frontend build first');
  }
  const bytes = entries.reduce((total, [, contents]) => total + contents.length, 0);
  const info = {
    name: appTitle(pkg),
    version: pkg.version,
    nodeVersion: process.version,
    builtAt: new Date().toISOString(),
    commit: process.env.GITHUB_SHA ? process.env.GITHUB_SHA.slice(0, 7) : null,
    files: entries.length,
    bytes,
  };
  const lines = [
    '/** Generated by scripts/build-standalone.mjs – do not edit. */',
    `export const BUILD_INFO = ${JSON.stringify(info, null, 2)};`,
    '',
    'export const EMBEDDED_APP = {',
    ...entries.map(([key, contents]) => `  ${JSON.stringify(key)}: '${contents.toString('base64')}',`),
    '};',
    '',
  ];
  fs.mkdirSync(buildDir, { recursive: true });
  const target = path.join(buildDir, 'embedded-app.mjs');
  fs.writeFileSync(target, lines.join('\n'));
  log(`embedded ${entries.length} files (${(bytes / 1024).toFixed(0)} KiB) from dist/`);
  return target;
}

async function bundleServer({ buildDir, embeddedModule }) {
  const outfile = path.join(buildDir, 'standalone.cjs');
  await esbuild({
    entryPoints: [path.join(APP_DIR, 'server', 'standalone.mjs')],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: `node${process.versions.node.split('.')[0]}`,
    alias: { '#app-bundle': embeddedModule },
    legalComments: 'none',
    logLevel: 'warning',
  });
  const size = fs.statSync(outfile).size;
  log(`bundled the server (${(size / 1024 / 1024).toFixed(1)} MiB)`);
  return outfile;
}

function createSeaBlob({ buildDir, bundlePath }) {
  const blob = path.join(buildDir, 'sea-prep.blob');
  const configPath = path.join(buildDir, 'sea-config.json');
  fs.writeFileSync(
    configPath,
    JSON.stringify({ main: bundlePath, output: blob, disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false }, null, 2),
  );
  log('generating the SEA blob');
  const result = spawnSync(process.execPath, ['--experimental-sea-config', configPath], { stdio: 'inherit' });
  if (result.status !== 0) throw new Error('generating the SEA blob failed');
  return blob;
}

async function nodeBinaryFor(name, cacheDir) {
  const target = TARGETS[name];
  if (target.platform === process.platform && target.arch === process.arch) return process.execPath;
  return ensureNodeBinary({
    version: process.versions.node,
    platform: target.platform,
    arch: target.arch,
    cacheDir,
  });
}

async function buildTarget({ name, outDir, blobPath, cacheDir }) {
  const target = TARGETS[name];
  const nodeBinary = await nodeBinaryFor(name, cacheDir);
  const output = path.join(outDir, `nmap2flowchart-${name}${target.extension}`);
  const staging = path.join(outDir, `nmap2flowchart-${name}-staging${target.extension}`);

  fs.copyFileSync(nodeBinary, staging);
  if (target.extension === '') fs.chmodSync(staging, 0o755);
  try {
    await inject(staging, 'NODE_SEA_BLOB', fs.readFileSync(blobPath), {
      sentinelFuse: SENTINEL_FUSE,
      overwrite: true,
    });
    fs.renameSync(staging, output);
  } catch (error) {
    fs.rmSync(staging, { force: true });
    if (error.code === 'EBUSY' || error.code === 'EPERM') {
      throw new Error(`${path.relative(REPO_DIR, output)} is in use – close the running copy and build again`);
    }
    throw error;
  }

  const size = fs.statSync(output).size;
  log(`wrote ${path.relative(REPO_DIR, output)} (${(size / 1024 / 1024).toFixed(0)} MiB)`);
  return output;
}

function copyRiskExample(directory) {
  if (!fs.existsSync(RISK_EXAMPLE)) return null;
  const target = path.join(directory, path.basename(RISK_EXAMPLE));
  fs.copyFileSync(RISK_EXAMPLE, target);
  log(`wrote ${path.relative(REPO_DIR, target)}`);
  return target;
}

function writeChecksums(artifacts) {
  const lines = artifacts.map((file) => {
    const digest = createHash('sha256').update(fs.readFileSync(file)).digest('hex');
    return `${digest}  ${path.basename(file)}`;
  });
  const target = path.join(path.dirname(artifacts[0]), 'SHA256SUMS.txt');
  fs.writeFileSync(target, `${lines.join('\n')}\n`);
  log(`wrote ${path.relative(REPO_DIR, target)}`);
}

function writeReleaseNotes({ outDir, entries, pkg }) {
  const platforms = {
    'win32-x64': 'Windows 10+ / x64',
    'win32-arm64': 'Windows 11 / arm64',
    'linux-x64': 'Linux / x64 (glibc 2.28+)',
    'linux-arm64': 'Linux / arm64 (glibc 2.28+)',
  };
  const lines = [
    `${appTitle(pkg)} ${pkg.version} – offline builds, generated ${new Date().toISOString().slice(0, 10)}`,
    '',
    ...entries.map(({ file, name }) => {
      const target = TARGETS[name];
      return `  ${path.basename(file).padEnd(26)} ${platforms[`${target.platform}-${target.arch}`]}`;
    }),
    '',
    'Run the file for your machine. It serves the editor on http://127.0.0.1:8080/ and',
    'opens your browser: no installer, no Node.js, no network access. Ctrl+C stops it.',
    '',
    '  --port <n>        listen on another port (0 picks a free one)',
    '  --host <addr>     bind elsewhere (default 127.0.0.1, this machine only)',
    '  --no-open         do not launch a browser',
    '  --auth            local accounts and project autosave (SQLite in your user',
    '                    profile directory; --data-dir moves it)',
    '  -h, -v            usage / version',
    '',
    'Risk levels (which ports turn a host red / orange / yellow) default to',
    'Critical / Medium / Low. Change them per diagram or per account in the editor',
    '(··· > Risk levels), or set the server-wide default with',
    '  NMAP_RISK_POLICY_FILE=/path/to/risk-policy.json   (see risk-policy.example.json)',
    '  NMAP_RISK_LEVELS=\'[{"label":"Critical","color":"#e5484d","ports":"23, 445"}]\'',
    '',
    'Linux: run chmod +x on the downloaded binary first.',
    'Diagrams live in the browser storage unless --auth is used.',
    '',
    'These are unsigned local builds. On Windows, SmartScreen may warn because',
    'injecting the bundle invalidates the signature the official node.exe shipped with.',
    '',
    'If Windows 11 Smart App Control blocks this file, build the portable folders instead:',
    '  cd App && npm run standalone:portable',
    'They ship the same bundle beside an unmodified, signed node.exe plus start.cmd,',
    'which Smart App Control accepts.',
    'Checksums are in SHA256SUMS.txt.',
    '',
  ];
  const target = path.join(outDir, 'README.txt');
  fs.writeFileSync(target, lines.join('\n'));
  log(`wrote ${path.relative(REPO_DIR, target)}`);
}

function smokeTest(binary, extraArgs = []) {  const result = spawnSync(
    process.execPath,
    [path.join(APP_DIR, 'scripts', 'smoke-standalone.mjs'), binary, ...extraArgs],
    { stdio: 'inherit' },
  );
  if (result.status !== 0) throw new Error(`smoke test failed for ${path.basename(binary)}`);
}

function verifyLauncher(folder, name, pkg) {
  const target = TARGETS[name];
  if (target.platform !== process.platform) return;
  const script = path.join(folder, target.platform === 'win32' ? 'start.cmd' : 'start.sh');
  const result =
    target.platform === 'win32'
      ? spawnSync(process.env.ComSpec || 'cmd.exe', ['/c', script, '--version'], { encoding: 'utf8' })
      : spawnSync(script, ['--version'], { encoding: 'utf8' });
  const output = `${result.stdout ?? ''}${result.stderr ?? ''}`;
  if (result.status !== 0 || !output.includes(appTitle(pkg))) {
    throw new Error(`launcher check failed for ${path.basename(folder)}: ${output.trim()}`);
  }
  log(`launcher ok: ${path.basename(script)} in ${path.basename(folder)}`);
}

function windowsLauncher() {
  return [
    '@echo off',
    'rem Runs NMAP2Flowchart on the bundled node.exe. Nothing in this folder is patched,',
    'rem so the signature Windows Smart App Control checks stays intact.',
    'setlocal',
    '"%~dp0node.exe" "%~dp0app.cjs" %*',
    '',
  ].join('\r\n');
}

function posixLauncher() {
  return [
    '#!/bin/sh',
    '# Runs NMAP2Flowchart on the bundled Node.js binary.',
    'exec "$(dirname "$0")/node" "$(dirname "$0")/app.cjs" "$@"',
    '',
  ].join('\n');
}

function portableReadme(name, target) {
  const lines = [
    `NMAP2Flowchart – portable ${target.platform}-${target.arch} build`,
    '',
    'Double-click start.cmd (Windows) or run ./start.sh (Linux). It serves the editor on',
    'http://127.0.0.1:8080/ and opens your browser. Ctrl+C stops it. All flags work,',
    'e.g. start.cmd --port 9000 --no-open --auth.',
    '',
    'Why a folder instead of one .exe? Windows Smart App Control refuses binaries whose',
    'publisher it cannot verify. The single-file build injects the app into node.exe,',
    'which invalidates that signature. Here node.exe stays untouched (OpenJS Foundation,',
    'signed) and only loads app.cjs, which contains the compiled app plus the API.',
    '',
    'Contents:',
    '  node.exe   official Node.js runtime, unmodified',
    '  app.cjs    NMAP2Flowchart (SPA + accounts API) as one bundle',
    '  start.cmd  launcher (start.sh on Linux)',
    '  risk-policy.example.json   server-wide risk levels for NMAP_RISK_POLICY_FILE',
    '',
    'Risk levels default to Critical / Medium / Low and can be changed per diagram or',
    'per account in the editor (··· > Risk levels). For a server-wide default, copy',
    'risk-policy.example.json somewhere, edit it, and set before starting:',
    '  NMAP_RISK_POLICY_FILE=/path/to/risk-policy.json   (or NMAP_RISK_LEVELS as JSON)',
    '',
  ];
  if (target.platform !== 'win32') lines.push('Linux: chmod +x node start.sh first.', '');
  return lines.join('\n');
}

async function buildPortable({ name, outDir, bundlePath, cacheDir }) {
  const target = TARGETS[name];
  const folder = path.join(outDir, `nmap2flowchart-portable-${name}`);
  const executableName = target.extension === '.exe' ? 'node.exe' : 'node';

  fs.rmSync(folder, { recursive: true, force: true });
  fs.mkdirSync(folder, { recursive: true });

  fs.copyFileSync(await nodeBinaryFor(name, cacheDir), path.join(folder, executableName));
  fs.copyFileSync(bundlePath, path.join(folder, 'app.cjs'));
  fs.writeFileSync(path.join(folder, 'README.txt'), portableReadme(name, target), 'utf8');
  copyRiskExample(folder);

  if (target.platform === 'win32') {
    fs.writeFileSync(path.join(folder, 'start.cmd'), windowsLauncher(), 'utf8');
  } else {
    const launcher = path.join(folder, 'start.sh');
    fs.writeFileSync(launcher, posixLauncher(), 'utf8');
    fs.chmodSync(launcher, 0o755);
    fs.chmodSync(path.join(folder, executableName), 0o755);
  }

  log(`wrote ${path.relative(REPO_DIR, folder)}${path.sep}`);
  return folder;
}

async function main() {
  const values = parseCli(process.argv.slice(2));
  const targets = resolveTargets(values.target);
  const outDir = path.resolve(REPO_DIR, values.out ?? 'release');
  const buildDir = path.resolve(APP_DIR, values['build-dir'] ?? path.join('build', 'sea'));
  const cacheDir = path.join(buildDir, 'cache');
  const pkg = readPackage();

  if (!values['skip-frontend']) buildFrontend();

  const files = collectFiles(path.join(APP_DIR, 'dist'));
  const embeddedModule = writeEmbeddedModule({ buildDir, files, pkg });
  const bundlePath = await bundleServer({ buildDir, embeddedModule });

  if (values['bundle-only'] === true) {
    fs.mkdirSync(outDir, { recursive: true });
    const appBundle = path.join(outDir, 'app.cjs');
    fs.copyFileSync(bundlePath, appBundle);
    const digest = createHash('sha256').update(fs.readFileSync(appBundle)).digest('hex');
    fs.writeFileSync(`${appBundle}.sha256`, `${digest}  app.cjs\n`);
    copyRiskExample(outDir);
    log(`wrote ${path.relative(REPO_DIR, appBundle)} (${(fs.statSync(appBundle).size / 1024 / 1024).toFixed(1)} MiB)`);
    if (values['no-smoke'] !== true) smokeTest(process.execPath, ['--script', appBundle]);
    console.log(`\nDone. Run it with: node ${path.relative(REPO_DIR, appBundle)}`);
    return;
  }

  const blobPath = createSeaBlob({ buildDir, bundlePath });

  fs.mkdirSync(outDir, { recursive: true });
  const portable = values.portable === true;
  const artifacts = [];
  for (const name of targets) {
    if (portable) {
      artifacts.push({ name, file: await buildPortable({ name, outDir, bundlePath, cacheDir }) });
    } else {
      artifacts.push({ name, file: await buildTarget({ name, outDir, blobPath, cacheDir }) });
    }
  }
  if (!portable) {
    writeChecksums(artifacts.map((entry) => entry.file));
    writeReleaseNotes({ outDir, entries: artifacts, pkg });
  }
  copyRiskExample(outDir);

  const hostTarget = targets.find(
    (name) => TARGETS[name].platform === process.platform && TARGETS[name].arch === process.arch,
  );
  if (hostTarget && values['no-smoke'] !== true) {
    const artifact = artifacts.find((entry) => entry.name === hostTarget).file;
    if (portable) {
      const executableName = TARGETS[hostTarget].extension === '.exe' ? 'node.exe' : 'node';
      verifyLauncher(artifact, hostTarget, pkg);
      smokeTest(path.join(artifact, executableName), ['--script', path.join(artifact, 'app.cjs')]);
    } else {
      smokeTest(artifact);
    }
  }

  console.log(`\nDone. ${artifacts.length} ${portable ? 'portable folder(s)' : 'executable(s)'} in ${outDir}`);
}

main().catch((error) => {
  console.error(`\nStandalone build failed: ${error.message}`);
  process.exit(1);
});
